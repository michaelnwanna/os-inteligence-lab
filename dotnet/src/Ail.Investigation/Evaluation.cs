using System.Text;
using Ail.Detection;
using Ail.Ingestion;
using Ail.Schemas;
using Ail.Simulator;

namespace Ail.Investigation;

public sealed class RunResult
{
    public string Scenario { get; init; } = "";
    public int Seed { get; init; }
    public int Expected { get; init; }
    public int Incidents { get; init; }
    public int Tp { get; set; }
    public int Fp { get; set; }
    public int Fn { get; set; }
    public List<double> Latencies { get; } = new();
    public List<bool> CohortOk { get; } = new();
    public List<int?> TriggerRank { get; } = new();
    public List<bool> AiValid { get; } = new();
    public List<bool> CulpritTop1 { get; } = new();
}

/// <summary>Scores detection, cohort, correlation and agent quality against scenario ground truth.</summary>
public static class Evaluation
{
    /// <summary>Minutes around the true effect start in which an onset counts as a match.</summary>
    public static readonly (int Lo, int Hi) StartTolerance = (-5, 40);

    private static bool SameDims(Dictionary<string, string>? a, Dictionary<string, string>? b) =>
        a is null || b is null ? a is null && b is null : a.Count == b.Count && a.All(kv => b.TryGetValue(kv.Key, out var v) && v == kv.Value);

    public static RunResult Run(Scenario sc, int seed, int? devices)
    {
        using var store = new TelemetryStore();
        FleetSimulator.SimulateToStore(sc, store, devices, seed);
        var incidents = Workflow.RunAnalysis(store, new DetectionConfig(), save: false);
        var episodes = sc.Expected.AllEpisodes();
        var res = new RunResult { Scenario = sc.Id, Seed = seed, Expected = episodes.Count, Incidents = incidents.Count };
        var unmatched = incidents.ToList();
        foreach (var ep in episodes)
        {
            var start = TimeUtil.BucketOf(sc.Start) + ep.EffectStartMinute;
            var inWindow = unmatched.Where(i => TimeUtil.BucketOf(i.Onset) >= start + StartTolerance.Lo && TimeUtil.BucketOf(i.Onset) <= start + StartTolerance.Hi).ToList();
            var exact = inWindow.Where(i => SameDims(i.Cohorts.FirstOrDefault()?.Dimensions, ep.Cohort)).ToList();
            var candidates = exact.Count > 0 ? exact : inWindow;
            if (candidates.Count == 0) { res.Fn++; continue; }
            var inc = candidates.MinBy(i => Math.Abs(TimeUtil.BucketOf(i.Onset) - start))!;
            unmatched.Remove(inc);
            res.Tp++;
            res.Latencies.Add(TimeUtil.BucketOf(inc.FirstDetection) - start);
            var got = inc.Cohorts.FirstOrDefault()?.Dimensions;
            res.CohortOk.Add(ep.Cohort is not null ? SameDims(got, ep.Cohort) : got is null);
            if (ep.Trigger is not null)
            {
                var ids = inc.Correlations.Select(c => c.Change.DeploymentId).ToList();
                var ix = ids.IndexOf(ep.Trigger);
                res.TriggerRank.Add(ix >= 0 ? ix + 1 : null);
            }
            if (inc.Investigation is { } inv)
            {
                res.AiValid.Add(inv.Guardrail.TryGetValue("provider_output_valid", out var v) && Equals(v, true));
                if (ep.CulpritCommit is not null)
                    res.CulpritTop1.Add(inv.CandidateCommits.Count > 0 && inv.CandidateCommits[0].Sha == ep.CulpritCommit);
            }
        }
        res.Fp = unmatched.Count;
        return res;
    }

    private static string Rate(double num, double den) => den > 0 ? $"{num / den * 100:0}% ({(int)num}/{(int)den})" : "n/a";

    private static double Median(List<double> xs)
    {
        var s = xs.OrderBy(x => x).ToList();
        return s.Count % 2 == 1 ? s[s.Count / 2] : (s[s.Count / 2 - 1] + s[s.Count / 2]) / 2;
    }

    public static string Report(IReadOnlyList<RunResult> runs, int scenarios, int seeds, int? devices, bool heldout = false)
    {
        double tp = runs.Sum(r => r.Tp), fp = runs.Sum(r => r.Fp), fn = runs.Sum(r => r.Fn);
        var precision = tp + fp > 0 ? tp / (tp + fp) : 1.0;
        var recall = tp + fn > 0 ? tp / (tp + fn) : 1.0;
        var f1 = precision + recall > 0 ? 2 * precision * recall / (precision + recall) : 0.0;
        var clean = runs.Where(r => r.Expected == 0).ToList();
        var lat = runs.SelectMany(r => r.Latencies).ToList();
        var cohort = runs.SelectMany(r => r.CohortOk).ToList();
        var ranks = runs.SelectMany(r => r.TriggerRank).ToList();
        var ai = runs.SelectMany(r => r.AiValid).ToList();
        var culprit = runs.SelectMany(r => r.CulpritTop1).ToList();
        var sb = new StringBuilder();
        void L(string s = "") => sb.Append(s).Append('\n');
        L(heldout ? "# Held-out benchmark results (.NET edition)" : "# Benchmark results (.NET edition)");
        L();
        var fleet = devices is { } d ? $"{d:N0} simulated devices each" : "each scenario's own fleet size";
        var note = heldout ? " Held-out scenarios were written after the detector settings were fixed and were never used for tuning." : "";
        L($"Generated by `ail evaluate{(heldout ? " --heldout" : "")}` ({scenarios} scenarios x {seeds} seeds, {fleet}, {runs.Sum(r => r.Expected)} injected regressions in total).{note}");
        L();
        L("## Detection"); L("| Metric | Result |"); L("|---|---|");
        L($"| Incident precision | {precision:0.00} |"); L($"| Incident recall | {recall:0.00} |"); L($"| F1 | {f1:0.00} |");
        L($"| False-positive rate (clean runs with any incident) | {Rate(clean.Count(r => r.Incidents > 0), clean.Count)} |");
        L(lat.Count > 0 ? $"| Detection latency from effect start (median / max, minutes) | {Median(lat):0} / {lat.Max():0} |" : "| Detection latency | n/a |");
        L();
        L("## Cohort intelligence"); L("| Metric | Result |"); L("|---|---|");
        L($"| Affected-cohort identification accuracy (exact dimensions) | {Rate(cohort.Count(x => x), cohort.Count)} |");
        L();
        L("## Correlation"); L("| Metric | Result |"); L("|---|---|");
        L($"| True change ranked top-1 | {Rate(ranks.Count(x => x == 1), ranks.Count)} |");
        L($"| True change ranked top-3 | {Rate(ranks.Count(x => x is <= 3), ranks.Count)} |");
        L();
        L("## AI investigation (default offline `rules` provider)"); L("| Metric | Result |"); L("|---|---|");
        L($"| Reports passing grounding validation | {Rate(ai.Count(x => x), ai.Count)} |");
        L($"| Deliberately injected commit ranked first | {Rate(culprit.Count(x => x), culprit.Count)} |");
        L();
        L("## Per-run detail");
        L("| Scenario | Seed | Expected | Incidents | Matched | Latency (min) | Cohort correct | Trigger rank |");
        L("|---|---|---|---|---|---|---|---|");
        foreach (var r in runs)
            L($"| {r.Scenario} | {r.Seed} | {r.Expected} | {r.Incidents} | {r.Tp} | {string.Join(", ", r.Latencies.Select(x => ((int)x).ToString()))} | " +
              $"{string.Join(", ", r.CohortOk)} | {string.Join(", ", r.TriggerRank.Select(x => x?.ToString() ?? "-"))} |");
        return sb.ToString();
    }

    public static string Evaluate(int? devices = 50_000, int seeds = 3, Action<string>? progress = null, bool heldout = false)
    {
        var scenarios = heldout ? ScenarioLoader.LoadHeldout() : ScenarioLoader.LoadAll();
        var runs = new List<RunResult>();
        foreach (var sc in scenarios)
            for (var k = 0; k < seeds; k++)
            {
                progress?.Invoke($"  {sc.Id} seed {sc.Seed + k}");
                runs.Add(Run(sc, sc.Seed + k, devices));
            }
        return Report(runs, scenarios.Count, seeds, devices, heldout);
    }
}
