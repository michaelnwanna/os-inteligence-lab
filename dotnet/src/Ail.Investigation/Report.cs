using System.Text;
using Ail.Detection;
using Ail.Schemas;

namespace Ail.Investigation;

public static class Report
{
    private static string Hm(DateTimeOffset dt) => dt.ToString("HH:mm");

    public static string RenderMarkdown(Incident inc)
    {
        var inv = inc.Investigation;
        var dims = inc.Cohorts.FirstOrDefault()?.Dimensions;
        var sb = new StringBuilder();
        sb.AppendLine($"# Incident {inc.Id}: {inc.Title}").AppendLine();
        sb.AppendLine($"**Status:** {Title(inc.Status)}  |  **Severity:** {Title(inc.Severity)}  |  **First detection:** {Hm(inc.FirstDetection)} UTC").AppendLine();
        sb.AppendLine($"**{Labels.MetricLabel(inc.Metric)}:** {Labels.FormatValue(inc.Metric, inc.Baseline)} -> {Labels.FormatValue(inc.Metric, inc.Observed)}  |  **Affected cohort:** {Labels.CohortLabel(dims)}");
        if (inc.Correlations.Count > 0)
        {
            var c = inc.Correlations[0];
            sb.AppendLine($"**Likely trigger:** {c.Change.Component} {c.Change.ToVersion} ({c.Change.Kind.Replace('_', ' ')})  |  **Correlation:** {c.Score * 100:F0}%");
        }
        if (inv is not null)
        {
            sb.AppendLine().AppendLine("## Observed facts (deterministic analysis)");
            foreach (var e in inv.ObservedFacts) sb.AppendLine($"- **{e.Id}** {e.Statement}");
            sb.AppendLine().AppendLine($"## Hypotheses (generated by `{inv.Provider}`; not verified facts)");
            foreach (var h in inv.Hypotheses)
                sb.AppendLine($"- **[{h.Confidence} confidence]** {h.Title}  \n  {h.Rationale}  \n  _Evidence: {string.Join(", ", h.SupportingEvidence)}_");
            sb.AppendLine().AppendLine("## Recommended investigation");
            for (var i = 0; i < inv.RecommendedSteps.Count; i++)
                sb.AppendLine($"{i + 1}. {inv.RecommendedSteps[i].Step} _({string.Join(", ", inv.RecommendedSteps[i].Evidence)})_");
            if (inv.CandidateCommits.Count > 0)
            {
                sb.AppendLine().AppendLine("## Candidate commits (heuristic review)");
                foreach (var c in inv.CandidateCommits) sb.AppendLine($"{c.Rank}. `{c.Sha[..7]}` {c.Message} (score {c.Score:F2}, {c.Component ?? "n/a"})");
            }
        }
        sb.AppendLine().AppendLine("## Reproducibility");
        sb.AppendLine($"Config `{inc.Reproducibility.GetValueOrDefault("config_hash")}`, data `{inc.Reproducibility.GetValueOrDefault("data_fingerprint")}`, engine {inc.Reproducibility.GetValueOrDefault("engine_version")}.");
        return sb.ToString();
    }

    private static string Title(string s) => s.Length == 0 ? s : char.ToUpperInvariant(s[0]) + s[1..];
}
