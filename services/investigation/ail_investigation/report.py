"""Human-readable reports and GitHub issue drafts."""

from __future__ import annotations

from ail_detection.labels import cohort_label, format_value, metric_label
from ail_schemas import Incident


def _facts(inc: Incident) -> list[str]:
    return [f"- **{e.id}** {e.statement}" for e in (inc.investigation.observed_facts if inc.investigation else [])]


def render_markdown(inc: Incident) -> str:
    inv = inc.investigation
    dims = inc.cohorts[0].dimensions if inc.cohorts else {}
    lines = [
        f"# Incident {inc.id}: {inc.title}",
        "",
        f"**Status:** {inc.status.title()}  |  **Severity:** {inc.severity.title()}  |  "
        f"**First detection:** {inc.first_detection:%H:%M} UTC",
        "",
        f"**{metric_label(inc.metric)}:** {format_value(inc.metric, inc.baseline)} -> "
        f"{format_value(inc.metric, inc.observed)}  |  **Affected cohort:** {cohort_label(dims)}",
    ]
    if inc.correlations:
        c = inc.correlations[0]
        lines.append(f"**Likely trigger:** {c.change.component} {c.change.to_version or ''} "
                     f"({c.change.kind.replace('_', ' ')})  |  **Correlation:** {c.score * 100:.0f}%")
    if inv:
        lines += ["", "## Observed facts (deterministic analysis)", *_facts(inc), "",
                  f"## Hypotheses (generated by `{inv.provider}`; not verified facts)"]
        for h in inv.hypotheses:
            lines.append(f"- **[{h.confidence} confidence]** {h.title}  \n  {h.rationale}  \n  "
                         f"_Evidence: {', '.join(h.supporting_evidence)}_")
        lines += ["", "## Recommended investigation"]
        lines += [f"{i}. {s.step} _({', '.join(s.evidence)})_" for i, s in enumerate(inv.recommended_steps, 1)]
        if inv.candidate_commits:
            lines += ["", "## Candidate commits (heuristic review)"]
            for c in inv.candidate_commits:
                lines.append(f"{c.rank}. `{c.sha[:7]}` {c.message} (score {c.score:.2f}, {c.component or 'n/a'})")
    lines += ["", "## Reproducibility",
              f"Config `{inc.reproducibility.get('config_hash')}`, data `{inc.reproducibility.get('data_fingerprint')}`, "
              f"engine {inc.reproducibility.get('engine_version')}."]
    return "\n".join(lines) + "\n"


def render_issue(inc: Incident) -> tuple[str, str]:
    """(title, body) for a GitHub issue. Facts and AI hypotheses are labelled separately."""
    title = f"[{inc.id}] {inc.title}"
    inv = inc.investigation
    body = [
        f"Automatically drafted by OS Intelligence Lab. Severity: **{inc.severity}**.",
        "",
        "## Observed facts",
        *(_facts(inc) or ["_No investigation data._"]),
        "",
        "## AI-generated hypotheses (unverified)",
    ]
    if inv:
        body += [f"- ({h.confidence} confidence) **{h.title}**: {h.rationale} _[{', '.join(h.supporting_evidence)}]_"
                 for h in inv.hypotheses]
        body += ["", "## Suggested next steps", *[f"- {s.step}" for s in inv.recommended_steps]]
    body += ["", "> Correlation is evidence, not proof of causation. Confirm with a rollback or bisect."]
    return title, "\n".join(body)
